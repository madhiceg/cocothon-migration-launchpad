-- ============================================================
-- CoCoDuo Migration Expert: Assessment Data Fetch Queries
-- Run these queries to retrieve complete customer assessment data
-- ============================================================

-- 1. List all assessments (overview)
SELECT
    ASSESSMENT_ID,
    CUSTOMER_NAME,
    INDUSTRY,
    SA_NAME,
    SA_EMAIL,
    ARRAY_TO_STRING(SOURCE_SYSTEMS, ', ') AS SOURCE_SYSTEMS,
    TOTAL_DATA_SIZE_TB,
    TOTAL_TABLES,
    TOTAL_USERS,
    BUDGET_SENSITIVITY,
    TIMELINE,
    MIGRATION_APPROACH,
    SNOWFLAKE_EDITION,
    COMPLETENESS_PCT,
    STATUS,
    SUBMITTED_AT
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENTS
ORDER BY SUBMITTED_AT DESC;

-- 2. Full customer assessment (replace <ASSESSMENT_ID>)
SELECT *
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENTS
WHERE ASSESSMENT_ID = '<ASSESSMENT_ID>';

-- 3. Source system details for a customer
SELECT
    SOURCE_SYSTEM,
    VERSION,
    HOSTING,
    CONNECTIVITY,
    DATA_SIZE_GB,
    TABLE_COUNT,
    LARGEST_TABLE,
    SYSTEM_SPECIFIC_DETAILS,
    NOTES
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENT_SOURCE_SYSTEMS
WHERE ASSESSMENT_ID = '<ASSESSMENT_ID>'
ORDER BY DATA_SIZE_GB DESC;

-- 4. ETL tool details for a customer
SELECT
    TOOL_NAME,
    PIPELINE_COUNT,
    SATISFACTION,
    POST_MIGRATION_PLAN,
    NOTES
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENT_ETL_TOOLS
WHERE ASSESSMENT_ID = '<ASSESSMENT_ID>'
ORDER BY PIPELINE_COUNT DESC;

-- 5. Architecture nuances (critical context)
SELECT
    NUANCES_DATA:tooling_concerns::VARCHAR AS TOOLING_CONCERNS,
    NUANCES_DATA:cost_priorities::VARCHAR AS COST_PRIORITIES,
    NUANCES_DATA:technical_debt::VARCHAR AS TECHNICAL_DEBT,
    NUANCES_DATA:data_architecture_vision::VARCHAR AS ARCHITECTURE_VISION,
    NUANCES_DATA:performance_requirements::VARCHAR AS PERFORMANCE_REQS,
    NUANCES_DATA:security_requirements::VARCHAR AS SECURITY_REQS,
    NUANCES_DATA:migration_risks::VARCHAR AS RISKS,
    NUANCES_DATA:additional_context::VARCHAR AS ADDITIONAL_CONTEXT
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENTS
WHERE ASSESSMENT_ID = '<ASSESSMENT_ID>';

-- 6. Reference architectures (similar industry or source systems)
SELECT
    REFERENCE_ID,
    CUSTOMER_NAME,
    INDUSTRY,
    ARRAY_TO_STRING(SOURCE_SYSTEMS, ', ') AS SOURCES,
    SOLUTION_SUMMARY,
    ARCHITECTURE_DETAILS,
    LESSONS_LEARNED,
    ARRAY_TO_STRING(TAGS, ', ') AS TAGS
FROM MIGRATION_ASSESSMENTS.INTAKE.REFERENCE_ARCHITECTURES
WHERE INDUSTRY = '<INDUSTRY>'
   OR ARRAYS_OVERLAP(SOURCE_SYSTEMS,
        (SELECT SOURCE_SYSTEMS FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENTS
         WHERE ASSESSMENT_ID = '<ASSESSMENT_ID>'))
ORDER BY CREATED_AT DESC;

-- 7. Search customer by name (fuzzy)
SELECT ASSESSMENT_ID, CUSTOMER_NAME, INDUSTRY, SA_NAME
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENTS
WHERE UPPER(CUSTOMER_NAME) LIKE UPPER('%<SEARCH_TERM>%');

-- 8. Cross-customer analytics (tool satisfaction)
SELECT
    TOOL_NAME,
    COUNT(*) AS CUSTOMER_COUNT,
    LISTAGG(DISTINCT SATISFACTION, ', ') AS SATISFACTION_LEVELS,
    SUM(PIPELINE_COUNT) AS TOTAL_PIPELINES,
    LISTAGG(DISTINCT POST_MIGRATION_PLAN, ', ') AS PLANS
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENT_ETL_TOOLS
GROUP BY TOOL_NAME
ORDER BY CUSTOMER_COUNT DESC;

-- 9. Full assessment data as JSON (for export/report generation)
SELECT
    ASSESSMENT_ID,
    CUSTOMER_NAME,
    OBJECT_CONSTRUCT(
        'customer', CUSTOMER_DATA,
        'volume', VOLUME_DATA,
        'etl', ETL_DATA,
        'transformation', TRANSFORMATION_DATA,
        'nuances', NUANCES_DATA,
        'source_details', SOURCE_DETAILS
    ) AS FULL_PAYLOAD
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENTS
WHERE ASSESSMENT_ID = '<ASSESSMENT_ID>';

-- 10. Version history for a customer assessment
SELECT
    HISTORY_ID,
    ASSESSMENT_ID,
    VERSION_NUMBER,
    CUSTOMER_NAME,
    SA_NAME,
    CHANGE_SUMMARY,
    COMPLETENESS_PCT,
    STATUS,
    CREATED_AT,
    CREATED_BY
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENT_VERSION_HISTORY
WHERE ASSESSMENT_ID = '<ASSESSMENT_ID>'
ORDER BY VERSION_NUMBER DESC;

-- 11. Compare current vs historical versions
SELECT
    'CURRENT' AS SOURCE,
    a.ASSESSMENT_ID, a.VERSION_NUMBER, a.CUSTOMER_NAME,
    a.TOTAL_DATA_SIZE_TB, a.TOTAL_TABLES, a.COMPLETENESS_PCT,
    a.STATUS, a.UPDATED_AT AS TIMESTAMP
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENTS a
WHERE a.ASSESSMENT_ID = '<ASSESSMENT_ID>'
UNION ALL
SELECT
    'HISTORY v' || h.VERSION_NUMBER AS SOURCE,
    h.ASSESSMENT_ID, h.VERSION_NUMBER, h.CUSTOMER_NAME,
    NULL, NULL, h.COMPLETENESS_PCT,
    h.STATUS, h.CREATED_AT AS TIMESTAMP
FROM MIGRATION_ASSESSMENTS.INTAKE.ASSESSMENT_VERSION_HISTORY h
WHERE h.ASSESSMENT_ID = '<ASSESSMENT_ID>'
ORDER BY VERSION_NUMBER DESC;
